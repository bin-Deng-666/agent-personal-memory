import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
const check = process.argv.includes("--check");
const directory = "packages/pi/runtime";
await mkdir(directory, { recursive: true });
for (const [name, entry] of [
  ["extension", "packages/pi/src/extension.ts"],
  ["worker", "packages/pi/src/agents/worker.ts"],
]) {
  const outfile = `${directory}/${name}.ts`;
  const result = await build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node22",
    minify: true,
    legalComments: "eof",
    external: ["@earendil-works/*", "typebox"],
    banner: {
      js: '// Generated by npm run build:pi. Edit packages/pi/src or packages/core/src.\nimport {createRequire as __makeRequire} from "node:module";var require=__makeRequire(import.meta.url);',
    },
    metafile: true,
    write: !check,
  });
  if (
    Object.keys(result.metafile.inputs).some(
      (path) => path.includes("packages/claude-code") || path.includes("@modelcontextprotocol"),
    )
  )
    throw new Error("Pi package must not include the Claude runtime");
  if (check && result.outputFiles[0].text !== (await readFile(outfile, "utf8")))
    throw new Error("Pi runtime is stale; run npm run build:pi");
}
const runner = await readFile("packages/pi/src/agents/runner.mjs", "utf8");
if (check) {
  if ((await readFile(`${directory}/runner.mjs`, "utf8")) !== runner)
    throw new Error("Pi runner is stale");
} else await writeFile(`${directory}/runner.mjs`, runner);
console.log(
  `Pi runtime ${check ? "verified" : "built"}: shared core bundled, host SDK external, no Claude runtime.`,
);
