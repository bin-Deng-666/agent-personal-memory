import { build } from "esbuild";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
const options = {
  entryPoints: ["src/claude/main.ts"],
  outfile: "claude/runtime.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify: true,
  legalComments: "eof",
  banner: {
    js: '// Generated by npm run build:claude. Edit src/claude/, not this file.\nimport { createRequire as __createRequire } from "node:module";const require=__createRequire(import.meta.url);',
  },
  metafile: true,
};
const check = process.argv.includes("--check");
const result = await build({ ...options, write: !check });
if (Object.keys(result.metafile.inputs).some((path) => path.includes("@earendil-works")))
  throw new Error("Claude runtime must not depend on Pi");
if (check && result.outputFiles[0].text !== (await readFile(options.outfile, "utf8")))
  throw new Error("Claude runtime is stale; run npm run build:claude");
const dependencies = [
  ...new Set(
    Object.keys(result.metafile.inputs)
      .filter((path) => path.startsWith("node_modules/"))
      .map((path) => {
        const parts = path.split("/");
        return parts[1].startsWith("@") ? parts.slice(0, 3).join("/") : parts.slice(0, 2).join("/");
      }),
  ),
].sort();
const notices = [
  "# Third-party notices",
  "",
  "The standalone Claude runtime contains code from these packages. Generated by `npm run build:claude`.",
  "",
];
for (const directory of dependencies) {
  const metadata = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
  notices.push(
    `## ${metadata.name} ${metadata.version}`,
    "",
    `License: ${metadata.license || "see package license"}`,
    "",
  );
  const licenses = (await readdir(directory))
    .filter((name) => /^(?:licen[sc]e|copying|notice)(?:\.|$)/i.test(name))
    .sort();
  for (const name of licenses)
    notices.push("```text", (await readFile(join(directory, name), "utf8")).trim(), "```", "");
}
const noticeText = notices.join("\n");
if (check) {
  if ((await readFile("claude/THIRD_PARTY_NOTICES.md", "utf8")) !== noticeText)
    throw new Error("Third-party notices are stale; run npm run build:claude");
} else await writeFile("claude/THIRD_PARTY_NOTICES.md", noticeText);
console.log(
  `Claude runtime ${check ? "verified" : "built"}: self-contained, no Pi runtime dependency; ${dependencies.length} dependency notices.`,
);
